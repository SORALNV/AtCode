const FILLED = new Set(["play"]);

export function icon(name: string, size = 18): string {
  const path = PATHS[name] ?? "";
  const filled = FILLED.has(name);
  return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="${
    filled ? "currentColor" : "none"
  }" stroke="${
    filled ? "none" : "currentColor"
  }" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`;
}

/** Replace every element carrying data-icon with its rendered SVG (prepended). */
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-icon]").forEach((el) => {
    const size = el.dataset.iconSize ? Number(el.dataset.iconSize) : 18;
    el.insertAdjacentHTML("afterbegin", icon(el.dataset.icon!, size));
  });
}

export function fileIconName(name: string): string {
  return /\.(cpp|cc|cxx|hpp|h|py|rs|c|java|js|ts)$/.test(name)
    ? "file-code"
    : "file";
}
